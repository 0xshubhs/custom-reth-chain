// Command gen writes internal/sigs/bundled.txt, the signature list compiled
// into the explorer: internal/sigs/standards.txt (ERC-20/721/1155/3643/4337,
// Multicall, Safe, proxies, OpenZeppelin errors, ...) plus, optionally, the
// ABIs of your own contracts so their calls and events decode by name even
// before they are verified.
//
// Run from explorer/backend:
//
//	go run ./internal/sigs/gen                                  # standards only
//	go run ./internal/sigs/gen -contracts ../../path/to/foundry  # + your contracts (forge build)
//	go run ./internal/sigs/gen -forge-out ../../path/to/out      # + an existing forge out/
//	go run ./internal/sigs/gen -go-abis ../../app/chain           # + ABI literals in Go sources
//
// The output is sorted, names its sources and carries no date, so the same
// sources always give the same file.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"custom-reth-chain/explorer/backend/internal/sigs"
)

func main() {
	contracts := flag.String("contracts", "", "optional: a Foundry project to build with forge (with its lib/)")
	forgeOut := flag.String("forge-out", "", "optional: read this forge out/ directory instead of building")
	goABIs := flag.String("go-abis", "", "optional: comma-separated Go source trees whose ABI string literals are read")
	standards := flag.String("standards", "internal/sigs/standards.txt", "hand-kept standard signatures")
	out := flag.String("o", "internal/sigs/bundled.txt", "output file")
	flag.Parse()
	if err := run(*contracts, *forgeOut, *goABIs, *standards, *out); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run(contracts, forgeOut, goABIs, standards, out string) error {
	ix := sigs.NewIndex()

	nSol, err := readForge(ix, contracts, forgeOut)
	if err != nil {
		return err
	}

	var goLines []string
	var goDirs []string
	for _, dir := range strings.Split(goABIs, ",") {
		dir = strings.TrimSpace(dir)
		if dir == "" {
			continue
		}
		goDirs = append(goDirs, dir)
		files, abis, err := readGoABIs(ix, dir)
		if err != nil {
			return err
		}
		if abis == 0 {
			return fmt.Errorf("%s: no ABI literals found", dir)
		}
		goLines = append(goLines, fmt.Sprintf("#   %s: %d ABIs in %d Go files", repoRel(dir), abis, files))
	}
	sort.Strings(goLines)
	if len(goDirs) > 0 {
		// Contract versions that are no longer in the sources can still be on
		// chain: every version those files ever had in git history is read too.
		versions, abis, err := readGoHistory(ix, goDirs)
		if err != nil {
			return err
		}
		goLines = append(goLines, fmt.Sprintf("#   git history (HEAD) of those directories, every version of every file: %d ABIs in %d file versions", abis, versions))
	}

	std, err := os.ReadFile(standards)
	if err != nil {
		return err
	}
	stdIx, err := sigs.ParseList(string(std))
	if err != nil {
		return fmt.Errorf("%s: %w", standards, err)
	}
	ix.Merge(stdIx)

	header := "# Generated by `go run ./internal/sigs/gen`. Do not edit: change the sources, then run it again.\n" +
		"# Sources read:\n"
	if nSol > 0 {
		src := contracts
		if forgeOut != "" {
			src = forgeOut
		}
		header += fmt.Sprintf("#   %s: forge artifacts of %d source files (tests, scripts and forge-std skipped)\n", repoRel(src), nSol)
	}
	if len(goLines) > 0 {
		header += strings.Join(goLines, "\n") + "\n"
	}
	header += fmt.Sprintf("#   internal/sigs/standards.txt: %d signatures\n", stdIx.Len(sigs.Function)+stdIx.Len(sigs.Event)+stdIx.Len(sigs.Error))
	if err := os.WriteFile(out, []byte(header+ix.MarshalList()), 0o644); err != nil {
		return err
	}
	fmt.Fprintf(os.Stderr, "gen: wrote %s: %d functions, %d events, %d errors\n", out, ix.Len(sigs.Function), ix.Len(sigs.Event), ix.Len(sigs.Error))
	return nil
}

// readForge adds every artifact ABI of the contracts project and returns how
// many source files they came from.
func readForge(ix *sigs.Index, contracts, forgeOut string) (int, error) {
	if contracts == "" && forgeOut == "" {
		return 0, nil
	}
	if forgeOut == "" {
		tmp, err := os.MkdirTemp("", "sigs-forge-")
		if err != nil {
			return 0, err
		}
		defer os.RemoveAll(tmp)
		forgeOut = filepath.Join(tmp, "out")
		root, err := filepath.Abs(contracts)
		if err != nil {
			return 0, err
		}
		cmd := exec.Command("forge", "build", "--root", root, "--out", forgeOut, "--cache-path", filepath.Join(tmp, "cache"),
			"--skip", "test", "--skip", "script", "--quiet")
		cmd.Stdout, cmd.Stderr = os.Stderr, os.Stderr
		fmt.Fprintln(os.Stderr, "gen: forge build", root)
		if err := cmd.Run(); err != nil {
			return 0, fmt.Errorf("forge build: %w", err)
		}
	}
	sources := map[string]bool{}
	err := filepath.WalkDir(forgeOut, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if d.Name() == "build-info" {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(path, ".json") {
			return nil
		}
		raw, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		var art struct {
			ABI      json.RawMessage `json:"abi"`
			Metadata struct {
				Settings struct {
					CompilationTarget map[string]string `json:"compilationTarget"`
				} `json:"settings"`
			} `json:"metadata"`
		}
		if json.Unmarshal(raw, &art) != nil || len(art.ABI) == 0 {
			return nil
		}
		for src := range art.Metadata.Settings.CompilationTarget {
			if skipSol(src) {
				return nil
			}
			sources[src] = true
		}
		if err := ix.AddABI(art.ABI); err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		return nil
	})
	if err != nil {
		return 0, err
	}
	if len(sources) == 0 {
		return 0, fmt.Errorf("no artifacts in %s", forgeOut)
	}
	return len(sources), nil
}

func skipSol(src string) bool {
	return strings.HasPrefix(src, "lib/forge-std/") || strings.HasPrefix(src, "test/") || strings.HasPrefix(src, "script/") ||
		strings.HasSuffix(src, ".t.sol") || strings.HasSuffix(src, ".s.sol")
}

// readGoABIs adds every string literal of the non-test Go files under dir
// that is a JSON ABI. It returns the files and ABIs it took signatures from.
func readGoABIs(ix *sigs.Index, dir string) (int, int, error) {
	var paths []string
	err := filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() && isGoSource(path) {
			paths = append(paths, path)
		}
		return nil
	})
	if err != nil {
		return 0, 0, err
	}
	sort.Strings(paths)
	files, abis := 0, 0
	for _, p := range paths {
		src, err := os.ReadFile(p)
		if err != nil {
			return 0, 0, err
		}
		found, err := goFileABIs(ix, p, src)
		if err != nil {
			return 0, 0, err
		}
		if found > 0 {
			files++
			abis += found
		}
	}
	return files, abis, nil
}

func isGoSource(path string) bool {
	return strings.HasSuffix(path, ".go") && !strings.HasSuffix(path, "_test.go")
}

// goFileABIs adds the JSON ABI string literals of one Go source file.
func goFileABIs(ix *sigs.Index, name string, src []byte) (int, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, name, src, parser.SkipObjectResolution)
	if err != nil {
		return 0, fmt.Errorf("%s: %w", name, err)
	}
	found := 0
	var addErr error
	ast.Inspect(f, func(n ast.Node) bool {
		lit, ok := n.(*ast.BasicLit)
		if !ok || lit.Kind != token.STRING || addErr != nil {
			return true
		}
		s, err := strconv.Unquote(lit.Value)
		if err != nil || !looksLikeABI(s) {
			return true
		}
		if err := ix.AddABI([]byte(s)); err != nil {
			addErr = fmt.Errorf("%s: %w", fset.Position(lit.Pos()), err)
			return false
		}
		found++
		return true
	})
	return found, addErr
}

// readGoHistory reads every version of the non-test Go files under dirs
// that HEAD's history ever had (git log --raw, then git cat-file), read only.
// It returns the number of file versions that held ABIs, then the number of ABIs.
func readGoHistory(ix *sigs.Index, dirs []string) (int, int, error) {
	args := append([]string{"log", "--format=", "--raw", "--no-abbrev", "--no-renames", "HEAD", "--"}, dirs...)
	logOut, err := exec.Command("git", args...).Output()
	if err != nil {
		return 0, 0, fmt.Errorf("git log: %w", err)
	}
	blobs := map[string]string{} // blob id -> a path it had
	for _, line := range strings.Split(string(logOut), "\n") {
		// :<old mode> <new mode> <old blob> <new blob> <status>\t<path>
		meta, path, ok := strings.Cut(line, "\t")
		if !ok || !strings.HasPrefix(meta, ":") || !isGoSource(path) {
			continue
		}
		f := strings.Fields(meta)
		if len(f) < 5 {
			continue
		}
		for _, b := range f[2:4] {
			if strings.Trim(b, "0") != "" {
				blobs[b] = path
			}
		}
	}
	ids := make([]string, 0, len(blobs))
	for b := range blobs {
		ids = append(ids, b)
	}
	sort.Strings(ids)
	if len(ids) == 0 {
		return 0, 0, nil
	}
	cmd := exec.Command("git", "cat-file", "--batch")
	cmd.Stdin = strings.NewReader(strings.Join(ids, "\n") + "\n")
	catOut, err := cmd.Output()
	if err != nil {
		return 0, 0, fmt.Errorf("git cat-file: %w", err)
	}
	versions, abis := 0, 0
	rest := catOut
	for _, id := range ids {
		nl := strings.IndexByte(string(rest[:min(len(rest), 200)]), '\n')
		if nl < 0 {
			return 0, 0, fmt.Errorf("git cat-file: short output at %s", id)
		}
		hdr := strings.Fields(string(rest[:nl]))
		if len(hdr) != 3 || hdr[0] != id || hdr[1] != "blob" {
			return 0, 0, fmt.Errorf("git cat-file: unexpected header %q", rest[:nl])
		}
		size, err := strconv.Atoi(hdr[2])
		if err != nil || nl+1+size+1 > len(rest) {
			return 0, 0, fmt.Errorf("git cat-file: bad size for %s", id)
		}
		src := rest[nl+1 : nl+1+size]
		rest = rest[nl+1+size+1:]
		found, err := goFileABIs(ix, blobs[id]+"@"+id[:12], src)
		if err != nil {
			// An old version that no longer parses with this Go is skipped,
			// not fatal: it cannot hold anything the current files lack.
			fmt.Fprintln(os.Stderr, "gen: skipping", err)
			continue
		}
		if found > 0 {
			versions++
			abis += found
		}
	}
	return versions, abis, nil
}

// looksLikeABI is a JSON array of objects that each carry a "type".
func looksLikeABI(s string) bool {
	s = strings.TrimSpace(s)
	if !strings.HasPrefix(s, "[") {
		return false
	}
	var entries []map[string]json.RawMessage
	if json.Unmarshal([]byte(s), &entries) != nil || len(entries) == 0 {
		return false
	}
	for _, e := range entries {
		if _, ok := e["type"]; !ok {
			return false
		}
	}
	return true
}

// repoRel names a directory relative to the repository root (explorer/backend is
// three levels down), so the header does not depend on where the checkout is.
func repoRel(dir string) string {
	abs, err := filepath.Abs(dir)
	if err != nil {
		return dir
	}
	root, err := filepath.Abs("../../..")
	if err != nil {
		return dir
	}
	if rel, err := filepath.Rel(root, abs); err == nil && !strings.HasPrefix(rel, "..") {
		return filepath.ToSlash(rel)
	}
	return filepath.ToSlash(dir)
}
